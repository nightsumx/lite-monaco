function stringHash(s, hashVal) {
    hashVal = (((hashVal << 5) - hashVal) + 149417) | 0
    for (let i = 0; i < s.length; i++) hashVal = (((hashVal << 5) - hashVal) + s.charCodeAt(i)) | 0
    return hashVal
}
function firstNonWhitespaceIndex(s) {
    for (let i = 0; i < s.length; i++) { const c = s.charCodeAt(i); if (c !== 32 && c !== 9) return i }
    return -1
}
function lastNonWhitespaceIndex(s) {
    for (let i = s.length - 1; i >= 0; i--) { const c = s.charCodeAt(i); if (c !== 32 && c !== 9) return i }
    return -1
}

export class DiffChange {
    
    constructor(originalStart, originalLength, modifiedStart, modifiedLength) {
        this.originalStart = originalStart;
        this.originalLength = originalLength;
        this.modifiedStart = modifiedStart;
        this.modifiedLength = modifiedLength;
    }
    
    getOriginalEnd() {
        return this.originalStart + this.originalLength;
    }
    
    getModifiedEnd() {
        return this.modifiedStart + this.modifiedLength;
    }
}

